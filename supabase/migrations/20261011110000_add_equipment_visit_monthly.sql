create table if not exists public.equipment_visit_monthly (
  id bigint generated by default as identity primary key,
  year smallint not null check (year between 2000 and 2100),
  month smallint not null check (month between 1 and 12),
  location text not null check (location in ('北投', '大直')),
  mr_count integer not null default 0 check (mr_count >= 0),
  ct_count integer not null default 0 check (ct_count >= 0),
  us_count integer not null default 0 check (us_count >= 0),
  bmd_count integer not null default 0 check (bmd_count >= 0),
  dx_count integer not null default 0 check (dx_count >= 0),
  mg_count integer not null default 0 check (mg_count >= 0),
  total_clients integer not null default 0 check (total_clients >= 0),
  active_days integer not null default 0 check (active_days >= 0),
  demand_metrics jsonb not null default '{}'::jsonb,
  source_start_date date not null,
  source_end_date date not null,
  is_finalized boolean not null default false,
  updated_at timestamptz not null default now(),
  constraint equipment_visit_monthly_period_key unique (year, month, location),
  constraint equipment_visit_monthly_source_range check (source_end_date >= source_start_date)
);

create index if not exists equipment_visit_monthly_location_year_idx
  on public.equipment_visit_monthly (location, year, month);

alter table public.equipment_visit_monthly enable row level security;

revoke all on table public.equipment_visit_monthly from anon, authenticated;
grant select on table public.equipment_visit_monthly to authenticated;

drop policy if exists "Equipment visit summaries are viewable"
  on public.equipment_visit_monthly;
create policy "Equipment visit summaries are viewable"
  on public.equipment_visit_monthly
  for select
  to authenticated
  using (true);

comment on table public.equipment_visit_monthly is
  'Monthly equipment visits imported from Salesforce. Finalized rows are skipped by normal incremental sync.';
comment on column public.equipment_visit_monthly.total_clients is
  'Distinct reservation count across all included equipment categories; it is not the sum of equipment columns.';
