import { describe, expect, it } from "vitest";
import { SPECIAL_ROLES, StationDefault, SYSTEM_OFF, type Shift, type User } from "../types";
import {
  buildDutyTaskExchangeUpdates,
  getDutyTaskExchangeError,
  type DutyTaskExchangeInput,
} from "./dutyTaskExchange";

const requestor = {
  id: "requestor",
  capabilities: [SPECIAL_ROLES.OPENING, SPECIAL_ROLES.LATE],
} as User;
const target = {
  id: "target",
  capabilities: [SPECIAL_ROLES.OPENING, SPECIAL_ROLES.LATE],
} as User;
const shift = (
  userId: string,
  date: string,
  specialRoles: string[] = [],
  station: string = StationDefault.CT,
): Shift => ({ id: `${userId}-${date}`, userId, date, station, specialRoles });

const validInput = (): DutyTaskExchangeInput => ({
  requestor,
  target,
  startDate: "2026-12-01",
  returnDate: "2026-12-03",
  roleToSwap: SPECIAL_ROLES.OPENING,
  targetRoleToSwap: SPECIAL_ROLES.LATE,
  requestorAtStart: shift("requestor", "2026-12-01", [SPECIAL_ROLES.OPENING]),
  targetAtStart: shift("target", "2026-12-01"),
  requestorAtReturn: shift("requestor", "2026-12-03"),
  targetAtReturn: shift("target", "2026-12-03", [SPECIAL_ROLES.LATE]),
});

describe("duty task exchange", () => {
  it("allows qualified staff to exchange assigned tasks across two dates", () => {
    expect(getDutyTaskExchangeError(validInput())).toBeUndefined();
  });

  it("allows qualified staff to exchange tasks on the same date", () => {
    const input: DutyTaskExchangeInput = {
      ...validInput(),
      returnDate: "2026-12-01",
      targetAtStart: shift("target", "2026-12-01", [SPECIAL_ROLES.LATE]),
      requestorAtReturn: undefined,
      targetAtReturn: undefined,
    };

    expect(getDutyTaskExchangeError(input)).toBeUndefined();
    expect(buildDutyTaskExchangeUpdates(input)).toEqual([
      {
        ...input.requestorAtStart,
        specialRoles: [SPECIAL_ROLES.LATE],
        isRoleAutoGenerated: false,
      },
      {
        ...input.targetAtStart,
        specialRoles: [SPECIAL_ROLES.OPENING],
        isRoleAutoGenerated: false,
      },
    ]);
  });

  it("checks same-day compatibility after removing each person's outgoing task", () => {
    const input: DutyTaskExchangeInput = {
      ...validInput(),
      returnDate: "2026-12-01",
      requestorAtStart: shift("requestor", "2026-12-01", [
        SPECIAL_ROLES.OPENING,
        SPECIAL_ROLES.ASSIST,
      ]),
      targetAtStart: shift("target", "2026-12-01", [SPECIAL_ROLES.LATE]),
      requestorAtReturn: undefined,
      targetAtReturn: undefined,
    };

    expect(getDutyTaskExchangeError(input)).toContain("衝突");
  });

  it("rejects missing task assignments and off-day participants", () => {
    expect(
      getDutyTaskExchangeError({
        ...validInput(),
        targetAtReturn: shift("target", "2026-12-03"),
      }),
    ).toContain("已沒有");
    expect(
      getDutyTaskExchangeError({
        ...validInput(),
        requestorAtReturn: shift("requestor", "2026-12-03", [], SYSTEM_OFF),
      }),
    ).toContain("上班狀態");
  });

  it("rejects missing qualifications and incompatible roles or stations", () => {
    expect(
      getDutyTaskExchangeError({
        ...validInput(),
        target: { ...target, capabilities: [] },
      }),
    ).toContain("不具備");
    expect(
      getDutyTaskExchangeError({
        ...validInput(),
        targetAtStart: shift("target", "2026-12-01", [SPECIAL_ROLES.LATE]),
      }),
    ).toContain("衝突");
    expect(
      getDutyTaskExchangeError({
        ...validInput(),
        targetAtStart: shift("target", "2026-12-01", [SPECIAL_ROLES.DAZHI_SUPPORT]),
      }),
    ).toContain("衝突");
    expect(
      getDutyTaskExchangeError({
        ...validInput(),
        targetAtStart: shift("target", "2026-12-01", [], StationDefault.REMOTE),
      }),
    ).toContain("衝突");
    expect(
      getDutyTaskExchangeError({
        ...validInput(),
        requestorAtReturn: shift(
          "requestor",
          "2026-12-03",
          [],
          StationDefault.REMOTE,
        ),
      }),
    ).toContain("衝突");
  });

  it("changes only the exchanged tasks and preserves each shift's other data", () => {
    const input = validInput();
    input.targetAtStart!.specialRoles = [SPECIAL_ROLES.ASSIST];
    input.requestorAtReturn!.workTime = "08:00-16:00";

    expect(buildDutyTaskExchangeUpdates(input)).toEqual([
      {
        ...input.requestorAtStart,
        specialRoles: [],
        isRoleAutoGenerated: false,
      },
      {
        ...input.targetAtStart,
        specialRoles: [SPECIAL_ROLES.ASSIST, SPECIAL_ROLES.OPENING],
        isRoleAutoGenerated: false,
      },
      {
        ...input.targetAtReturn,
        specialRoles: [],
        isRoleAutoGenerated: false,
      },
      {
        ...input.requestorAtReturn,
        specialRoles: [SPECIAL_ROLES.LATE],
        isRoleAutoGenerated: false,
      },
    ]);
  });
});
