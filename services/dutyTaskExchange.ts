import { SPECIAL_ROLES, SYSTEM_OFF, type Shift, type User } from "../types";

export const DUTY_EXCHANGE_ROLES = [
  SPECIAL_ROLES.OPENING,
  SPECIAL_ROLES.LATE,
  SPECIAL_ROLES.ASSIST,
  SPECIAL_ROLES.SCHEDULER,
] as const;

type ExchangeUser = Pick<User, "id" | "capabilities">;

export interface DutyTaskExchangeInput {
  requestor: ExchangeUser;
  target: ExchangeUser;
  startDate: string;
  returnDate: string;
  roleToSwap: string;
  targetRoleToSwap: string;
  requestorAtStart?: Shift;
  targetAtStart?: Shift;
  requestorAtReturn?: Shift;
  targetAtReturn?: Shift;
}

const compatibleRolesByIncoming: Record<string, string[]> = {
  [SPECIAL_ROLES.OPENING]: [SPECIAL_ROLES.ASSIST, "配合銷假"],
  [SPECIAL_ROLES.LATE]: ["配合銷假"],
  [SPECIAL_ROLES.ASSIST]: [SPECIAL_ROLES.OPENING, "配合銷假"],
  [SPECIAL_ROLES.SCHEDULER]: ["配合銷假"],
};

const isWorking = (shift?: Shift) =>
  !!shift && ![SYSTEM_OFF, "OFF", "SYSTEM_OFF"].includes(shift.station);

function canReceiveRole(shift: Shift, role: string) {
  const existingRoles = shift.specialRoles || [];
  if (!DUTY_EXCHANGE_ROLES.includes(role as (typeof DUTY_EXCHANGE_ROLES)[number])) {
    return false;
  }
  if (existingRoles.includes(role)) return false;
  if (
    [SPECIAL_ROLES.OPENING, SPECIAL_ROLES.LATE].includes(
      role as (typeof SPECIAL_ROLES.OPENING | typeof SPECIAL_ROLES.LATE),
    ) &&
    (shift.station.includes("場控") ||
      shift.station.includes("遠") ||
      shift.station.includes("大直"))
  ) {
    return false;
  }
  return existingRoles.every((existing) =>
    compatibleRolesByIncoming[role]?.includes(existing),
  );
}

export function getDutyTaskExchangeError(
  input: DutyTaskExchangeInput,
): string | undefined {
  const {
    requestor,
    target,
    startDate,
    returnDate,
    roleToSwap,
    targetRoleToSwap,
    requestorAtStart,
    targetAtStart,
    requestorAtReturn,
    targetAtReturn,
  } = input;

  if (!startDate || !returnDate) return "請選擇兩個任務日期。";
  if (startDate === returnDate) return "任務互換的兩個日期不可相同。";
  if (requestor.id === target.id) return "不可與自己互換任務。";
  if (!DUTY_EXCHANGE_ROLES.includes(roleToSwap as (typeof DUTY_EXCHANGE_ROLES)[number])) {
    return "申請人的任務類型無法互換。";
  }
  if (!DUTY_EXCHANGE_ROLES.includes(targetRoleToSwap as (typeof DUTY_EXCHANGE_ROLES)[number])) {
    return "對方的任務類型無法互換。";
  }
  if (
    !isWorking(requestorAtStart) ||
    !isWorking(targetAtStart) ||
    !isWorking(requestorAtReturn) ||
    !isWorking(targetAtReturn)
  ) {
    return "雙方在兩個日期都必須是上班狀態。";
  }
  if (!(requestorAtStart.specialRoles || []).includes(roleToSwap)) {
    return `申請人在 ${startDate} 已沒有「${roleToSwap}」任務，請重新選擇。`;
  }
  if (!(targetAtReturn.specialRoles || []).includes(targetRoleToSwap)) {
    return `對方在 ${returnDate} 已沒有「${targetRoleToSwap}」任務，請重新選擇。`;
  }
  if (!target.capabilities?.includes(roleToSwap)) {
    return `對方不具備「${roleToSwap}」資格，無法互換。`;
  }
  if (!requestor.capabilities?.includes(targetRoleToSwap)) {
    return `申請人不具備「${targetRoleToSwap}」資格，無法互換。`;
  }
  if (!canReceiveRole(targetAtStart, roleToSwap)) {
    return `對方在 ${startDate} 的崗位或既有任務與「${roleToSwap}」衝突。`;
  }
  if (!canReceiveRole(requestorAtReturn, targetRoleToSwap)) {
    return `申請人在 ${returnDate} 的崗位或既有任務與「${targetRoleToSwap}」衝突。`;
  }
}

export function buildDutyTaskExchangeUpdates(input: DutyTaskExchangeInput): Shift[] {
  const error = getDutyTaskExchangeError(input);
  if (error) throw new Error(error);

  const {
    requestorAtStart,
    targetAtStart,
    requestorAtReturn,
    targetAtReturn,
    roleToSwap,
    targetRoleToSwap,
  } = input;

  return [
    {
      ...requestorAtStart!,
      specialRoles: (requestorAtStart!.specialRoles || []).filter(
        (role) => role !== roleToSwap,
      ),
      isRoleAutoGenerated: false,
    },
    {
      ...targetAtStart!,
      specialRoles: [...(targetAtStart!.specialRoles || []), roleToSwap],
      isRoleAutoGenerated: false,
    },
    {
      ...targetAtReturn!,
      specialRoles: (targetAtReturn!.specialRoles || []).filter(
        (role) => role !== targetRoleToSwap,
      ),
      isRoleAutoGenerated: false,
    },
    {
      ...requestorAtReturn!,
      specialRoles: [
        ...(requestorAtReturn!.specialRoles || []),
        targetRoleToSwap,
      ],
      isRoleAutoGenerated: false,
    },
  ];
}
